<?php
// php -d extension=... scripts/stubs.php > stubs/phpolars.php
// IDE stubs from the loaded extension's reflection data.

function type(?ReflectionType $t): string {
    return $t === null ? '' : ((string) $t) . ' ';
}

function params(ReflectionFunctionAbstract $f): string {
    $out = [];
    foreach ($f->getParameters() as $p) {
        $s = type($p->getType()) . ($p->isVariadic() ? '...' : '') . '$' . $p->getName();
        if ($p->isOptional() && !$p->isVariadic()) {
            $s .= ' = null';
        }
        $out[] = $s;
    }
    return implode(', ', $out);
}

$ext = new ReflectionExtension('php_polars');
$byNs = [];
foreach ($ext->getClasses() as $c) {
    $byNs[$c->getNamespaceName()][] = $c;
}
foreach ($ext->getFunctions() as $f) {
    $byNs[$f->getNamespaceName()][] = $f;
}
ksort($byNs);

echo "<?php\n\n// Generated by scripts/stubs.php from the php_polars extension. Do not edit.\n";
foreach ($byNs as $ns => $items) {
    echo "\nnamespace $ns {\n";
    foreach ($items as $item) {
        if ($item instanceof ReflectionClass) {
            $parent = $item->getParentClass();
            $extends = $parent ? ' extends \\' . $parent->getName() : '';
            echo "\n    class {$item->getShortName()}$extends\n    {\n";
            foreach ($item->getReflectionConstants() as $k) {
                if ($k->getDeclaringClass()->getName() === $item->getName()) {
                    echo '        public const ' . $k->getName() . ' = ' . var_export($k->getValue(), true) . ";\n";
                }
            }
            foreach ($item->getMethods() as $m) {
                if ($m->getDeclaringClass()->getName() !== $item->getName()) {
                    continue;
                }
                $static = $m->isStatic() ? 'static ' : '';
                $ret = $m->getReturnType() ? ': ' . $m->getReturnType() : '';
                echo "        public {$static}function {$m->getName()}(" . params($m) . "){$ret} {}\n";
            }
            echo "    }\n";
        } else {
            $ret = $item->getReturnType() ? ': ' . $item->getReturnType() : '';
            echo "\n    function {$item->getShortName()}(" . params($item) . "){$ret} {}\n";
        }
    }
    echo "}\n";
}
